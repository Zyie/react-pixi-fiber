import fs from 'node:fs';
import path from 'node:path';

import type { SidebarsConfig } from '@docusaurus/plugin-content-docs';

import { PACKAGE_TOPICS } from './plugins/example/catalogue.mts';
import { DOCS_SIDEBAR } from './scripts/generators/content/sidebar.mts';
import { SITE } from './scripts/paths.mts';

/** An item of a sidebar */
type SidebarItemConfig = Extract<SidebarsConfig[string], readonly unknown[]>[number];

/** A folder of examples the examples generator wrote, with the label and place of its `_category_.json` */
interface ExampleTopic {
  readonly id: string;
  readonly label: string;
  readonly position: number;
}

/** The topics of the examples, in their order: the folders of `content/examples` */
function exampleTopics(): ExampleTopic[] {
  const dir = path.join(SITE, 'content/examples');
  if (!fs.existsSync(dir)) return [];

  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory())
    .map((entry) => {
      const category = JSON.parse(fs.readFileSync(path.join(dir, entry.name, '_category_.json'), 'utf8')) as {
        label: string;
        position: number;
      };

      return { id: entry.name, label: category.label, position: category.position };
    })
    .sort((a, b) => a.position - b.position);
}

/**
 * A topic's folder in the sidebar
 * @param topic - The topic
 */
const topicCategory = ({ id, label }: ExampleTopic): SidebarItemConfig => ({
  type: 'category',
  label,
  collapsed: true,
  items: [{ type: 'autogenerated', dirName: `examples/${id}` }],
});

/**
 * The Examples sidebar, grouped by package as the navbar is: all examples, then core's, 2d's and 3d's,
 * then the r3f-style topics under three.js compat
 */
function examplesSidebar(): SidebarItemConfig[] {
  const topics = exampleTopics();
  const compat = topics.filter(({ id }) => !PACKAGE_TOPICS.includes(id));

  return [
    { type: 'doc', id: 'examples/index' },
    ...topics.filter(({ id }) => PACKAGE_TOPICS.includes(id)).map(topicCategory),
    ...(compat.length
      ? [{ type: 'category', label: 'three.js compat', collapsed: true, items: compat.map(topicCategory) } as const]
      : []),
  ];
}

/**
 * One sidebar per area, each the folder of `content/` with the same name. The navbar links each id,
 * so the ids stay; an area changes what's inside its own entry.
 */
const sidebars: SidebarsConfig = {
  docs: DOCS_SIDEBAR,
  examples: examplesSidebar(),
  api: [{ type: 'autogenerated', dirName: 'api' }],
};

export default sidebars;
